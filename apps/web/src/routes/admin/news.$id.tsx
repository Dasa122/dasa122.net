import type { postDetailSchema } from "@dasa122/contract";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { createFileRoute, useRouter } from "@tanstack/react-router";
import type { ReactNode } from "react";
import { AdminHeading } from "../../components/admin-heading";
import {
  PostEditor,
  type PostEditorInitial,
  type PostEditorValues,
} from "../../components/post-editor";
import { orpc } from "../../utils/orpc";

const frame = "mx-auto w-full max-w-[80rem] px-6 md:px-10";
const errorText = "font-mono text-[0.75rem] text-ember-text";

/** The id lookup reads the same list the index renders, one page deep. */
const adminPostLookupOptions = orpc.adminPosts.list.queryOptions({
  input: { limit: 100 },
});

type AdminPostDetail = ReturnType<typeof postDetailSchema.parse>;

export const Route = createFileRoute("/admin/news/$id")({
  component: EditPostPage,
  head: () => ({ meta: [{ title: "Edit post — Admin" }] }),
  loader: async ({ context, params }): Promise<AdminPostDetail | null> => {
    if (context.forbidden) {
      return null;
    }
    const data = await context.queryClient.ensureQueryData(
      adminPostLookupOptions,
    );
    return data.items.find((item) => item.id === params.id) ?? null;
  },
});

function AdminMessage({
  children,
  title,
}: {
  children: ReactNode;
  title: string;
}) {
  return (
    <main className="flex-1">
      <div className={frame}>
        <div className="pb-[clamp(4rem,10vw,9rem)] pt-6">
          <AdminHeading title={title} />
          <div className="glass-card mt-8 max-w-[62rem] p-6 sm:p-8">
            <p className="text-lg leading-relaxed text-ink">{children}</p>
          </div>
        </div>
      </div>
    </main>
  );
}

function EditPostPage() {
  // The router does not infer this route's loader type in this setup, so the
  // runtime data is re-typed the way `news.$slug` does.
  const post = Route.useLoaderData() as AdminPostDetail | null;
  const { id } = Route.useParams();
  const router = useRouter();
  const queryClient = useQueryClient();

  const update = useMutation(orpc.adminPosts.update.mutationOptions());
  const publish = useMutation(orpc.adminPosts.publish.mutationOptions());
  const unpublish = useMutation(orpc.adminPosts.unpublish.mutationOptions());

  const refresh = () => {
    void queryClient.invalidateQueries({
      queryKey: orpc.adminPosts.list.key(),
    });
    void router.invalidate();
  };

  const save = (values: PostEditorValues) =>
    update.mutate({ id, ...values }, { onSuccess: refresh });

  const publishNow = (values: PostEditorValues) => {
    if (post?.status === "published") {
      // Unpublish withdraws the row without writing the form first: an edit
      // should not go live on the way out.
      unpublish.mutate({ id }, { onSuccess: refresh });
      return;
    }
    update.mutate(
      { id, ...values },
      { onSuccess: () => publish.mutate({ id }, { onSuccess: refresh }) },
    );
  };

  if (post === null) {
    return <AdminMessage title="News">That post does not exist.</AdminMessage>;
  }

  if (post.source === "github") {
    return (
      <AdminMessage title="Edit post">
        This post was generated by the GitHub sync and is read-only.
      </AdminMessage>
    );
  }

  const initial: PostEditorInitial = {
    body: post.body ?? "",
    coverImage: post.coverImage ?? "",
    excerpt: post.excerpt ?? "",
    id: post.id,
    slug: post.slug,
    source: post.source,
    status: post.status,
    tags: post.tags,
    title: post.title,
  };

  const isPending =
    update.isPending || publish.isPending || unpublish.isPending;

  return (
    <main className="flex-1">
      <div className={frame}>
        <div className="pb-[clamp(4rem,10vw,9rem)] pt-6">
          <AdminHeading title="Edit post" />

          <div className="glass-card mt-8 max-w-[62rem] p-6 sm:p-8">
            {(update.isError || publish.isError || unpublish.isError) && (
              <p className={`mb-6 ${errorText}`}>Could not save the post.</p>
            )}

            <PostEditor
              initial={initial}
              isPending={isPending}
              onPublish={publishNow}
              onSave={save}
            />
          </div>
        </div>
      </div>
    </main>
  );
}
