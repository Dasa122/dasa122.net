import { Button } from "@dasa122/ui";
import { useState } from "react";

/** The values the editor hands back to its consumer on save or publish. */
export type PostEditorValues = {
  body: string;
  coverImage: string | null;
  excerpt: string | null;
  slug: string | null;
  source: "own" | "linkedin";
  tags: string[];
  title: string;
};

/** The post an editor starts from. `id` is null for a new post. */
export type PostEditorInitial = {
  body: string;
  coverImage: string;
  excerpt: string;
  id: string | null;
  slug?: string | null;
  source: "own" | "linkedin";
  status: "draft" | "published";
  tags: string[];
  title: string;
};

const label =
  "block font-mono text-[0.6875rem] uppercase tracking-[0.14em] text-muted";
const field = "admin-field";
const errorText = "font-mono text-[0.75rem] text-ember-text";

/** A trimmed value, or null when the field is blank. */
function optional(value: string): string | null {
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function commaSeparated(value: string): string[] {
  return value
    .split(",")
    .map((tag) => tag.trim())
    .filter((tag) => tag.length > 0);
}

/**
 * The draft editor. It is a controlled form with no background saving: the post
 * is only written when one of the two actions is pressed. Both actions are
 * disabled while the consumer's mutation is in flight.
 *
 * The source is limited to the two sources a person can write. A GitHub post is
 * generated by the sync worker and is never editable, so the editor is never
 * reachable for one.
 */
export function PostEditor({
  initial,
  onSave,
  onPublish,
  isPending,
}: {
  initial: PostEditorInitial;
  onSave: (values: PostEditorValues) => void;
  onPublish: (values: PostEditorValues) => void;
  isPending: boolean;
}) {
  const [title, setTitle] = useState(initial.title);
  const [slug, setSlug] = useState(initial.slug ?? "");
  const [body, setBody] = useState(initial.body);
  const [excerpt, setExcerpt] = useState(initial.excerpt);
  const [tags, setTags] = useState(initial.tags.join(", "));
  const [coverImage, setCoverImage] = useState(initial.coverImage);
  const [source, setSource] = useState<"own" | "linkedin">(initial.source);
  const [error, setError] = useState<string | null>(null);

  const values = (): PostEditorValues => ({
    body,
    coverImage: optional(coverImage),
    excerpt: optional(excerpt),
    slug: optional(slug),
    source,
    tags: commaSeparated(tags),
    title: title.trim(),
  });

  // The buttons are `type="button"`, so the native `required` attribute never
  // runs; this is the guard that turns an empty title into a specific message.
  const dispatch = (action: (values: PostEditorValues) => void) => {
    const next = values();
    if (next.title.length === 0) {
      setError("Title is required.");
      return;
    }
    setError(null);
    action(next);
  };

  // Editing a published post writes it live, so `Save draft` would be a lie.
  const saveLabel =
    initial.status === "published" ? "Save changes" : "Save draft";
  const publishLabel = initial.status === "published" ? "Unpublish" : "Publish";

  return (
    <form
      className="max-w-[56rem]"
      onSubmit={(event) => {
        event.preventDefault();
        dispatch(onSave);
      }}
    >
      <div className="space-y-8">
        <div>
          <label className={label} htmlFor="post-title">
            Title
          </label>
          <input
            className={field}
            id="post-title"
            onChange={(event) => setTitle(event.target.value)}
            required
            type="text"
            value={title}
          />
        </div>

        <div>
          <label className={label} htmlFor="post-slug">
            Slug <span className="normal-case tracking-normal">(optional)</span>
          </label>
          <input
            className={field}
            id="post-slug"
            onChange={(event) => setSlug(event.target.value)}
            type="text"
            value={slug}
          />
        </div>

        <div>
          <label className={label} htmlFor="post-body">
            Body <span className="normal-case tracking-normal">(markdown)</span>
          </label>
          <textarea
            className={`${field} min-h-64 resize-y font-mono text-[0.875rem]`}
            id="post-body"
            onChange={(event) => setBody(event.target.value)}
            value={body}
          />
        </div>

        <div>
          <label className={label} htmlFor="post-excerpt">
            Excerpt{" "}
            <span className="normal-case tracking-normal">(optional)</span>
          </label>
          <textarea
            className={field}
            id="post-excerpt"
            onChange={(event) => setExcerpt(event.target.value)}
            rows={2}
            value={excerpt}
          />
        </div>

        <div>
          <label className={label} htmlFor="post-tags">
            Tags{" "}
            <span className="normal-case tracking-normal">
              (comma-separated)
            </span>
          </label>
          <input
            className={field}
            id="post-tags"
            onChange={(event) => setTags(event.target.value)}
            type="text"
            value={tags}
          />
        </div>

        <div>
          <label className={label} htmlFor="post-cover">
            Cover image URL{" "}
            <span className="normal-case tracking-normal">(optional)</span>
          </label>
          <input
            className={field}
            id="post-cover"
            onChange={(event) => setCoverImage(event.target.value)}
            type="text"
            value={coverImage}
          />
        </div>

        <div>
          <label className={label} htmlFor="post-source">
            Source
          </label>
          <select
            className={field}
            id="post-source"
            onChange={(event) =>
              setSource(event.target.value as "own" | "linkedin")
            }
            value={source}
          >
            <option value="own">Note</option>
            <option value="linkedin">LinkedIn</option>
          </select>
        </div>
      </div>

      {error && <p className={`mt-6 ${errorText}`}>{error}</p>}

      <div className="mt-10 flex flex-wrap items-baseline gap-x-6 gap-y-3">
        <Button
          disabled={isPending}
          onClick={() => dispatch(onSave)}
          variant="quiet"
        >
          {saveLabel}
        </Button>
        <Button
          disabled={isPending}
          onClick={() => dispatch(onPublish)}
          variant="solid"
        >
          {publishLabel}
        </Button>
      </div>
    </form>
  );
}
